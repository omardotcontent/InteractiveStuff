package omar.projects.interactivestuff.handlers.config;

/** One pixel family for navigation, actions and checkbox states; no font glyph substitutes. */
public enum SettingsIcon {
    GENERAL("..#..#..", "########", "..#..#..", "........", ".#...#..", "########", ".#...#..", "........"),
    PARTICLES("...#....", ".#.#..#.", "..###...", "#######.", "..###...", ".#.#..#.", "...#....", "......#."),
    SCRIPTING("..#..#..", ".#....#.", "#......#", ".#....#.", "..#..#..", "........", "..####..", "........"),
    MATERIALS(".######.", ".######.", "...##...", "...##...", "...##...", "...##...", "...##...", "...##..."),
    EXCLUSIONS(".######.", "##....##", "#.#....#", "#..#...#", "#...#..#", "#....#.#", "##....##", ".######."),
    PACKS("..####..", ".#....#.", "########", "#..##..#", "#..##..#", "#......#", "#......#", "########"),
    CHECK("........", ".......#", "......##", "#....##.", "##..##..", ".####...", "..##....", "........"),
    UNCHECKED("........", ".######.", ".#....#.", ".#....#.", ".#....#.", ".#....#.", ".######.", "........"),
    CLOSE("#......#", "##....##", ".##..##.", "..####..", "..####..", ".##..##.", "##....##", "#......#"),
    RESET(".#..###.", ".###...#", ".##....#", ".###....", "........", "#......#", "#.....#.", ".#####.."),
    FOLDER(".###....", "#...###.", "########", "#......#", "#......#", "#......#", "#......#", "########"),
    ADD("...##...", "...##...", "...##...", "########", "########", "...##...", "...##...", "...##..."),
    REMOVE("..####..", "########", ".#....#.", ".#.#..#.", ".#..#.#.", ".#.#..#.", ".#....#.", "..####.."),
    EDIT("......#.", ".....###", "....###.", "...###..", "..###...", ".###....", "###.....", "##......"),
    BACK("...#....", "..##....", ".##.....", "########", "########", ".##.....", "..##....", "...#...."),
    PREVIEW("..#.....", "..##....", "..###...", "..####..", "..####..", "..###...", "..##....", "..#....."),
    NEXT("....#...", "....##..", ".....##.", "########", "########", ".....##.", "....##..", "....#..."),
    ITEMS("########", "#.#.#..#", "########", "#.#.#..#", "########", "#.#.#..#", "########", "........"),
    SOUND("...#..#.", "..##...#", "####.#.#", "####.#.#", "####.#.#", "####.#.#", "..##...#", "...#..#.");

    private final String[] pixels;
    SettingsIcon(String... pixels) { this.pixels = pixels; }
    public void draw(SettingsScreen.Painter graphics, int x, int y, int color) {
        for (int row = 0; row < pixels.length; row++) for (int column = 0; column < pixels[row].length(); column++)
            if (pixels[row].charAt(column) == '#') graphics.fill(x + column, y + row, x + column + 1, y + row + 1, color);
    }
}
